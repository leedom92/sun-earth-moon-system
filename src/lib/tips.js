/**
 * tips.js —— 根据当前天象生成"小知识"文案（给小学生/初中生看的大白话）
 */
import { R2D } from './astro.js';

export function tipFor(st) {
  if (st.solar.type === 'total')
    return '日全食：月球离地球比较近，看上去和太阳一样大，本影锥正好够到地面。站在影子里的人会看到天色变暗、星星出现，还能看到平时看不见的太阳外层大气——日冕。';
  if (st.solar.type === 'annular')
    return '日环食：这次月球离地球比较远，看上去比太阳小一点，本影锥够不到地面。月亮只遮住太阳中间，边缘留下一圈明亮的光环，所以叫"环食"。';
  if (st.solar.type === 'partial')
    return '日偏食：月球的影子只擦过地球的一部分，被擦到的地方看到太阳被"咬"掉一块。日食一定发生在农历初一（朔）。';
  if (st.lunar.type === 'total')
    return '月全食：整个月亮都钻进了地球的本影。这时月亮并不全黑，而是暗红色——因为地球大气把红光折射进了影子里，所以月全食又叫"血月"。';
  if (st.lunar.type === 'partial')
    return '月偏食：月亮的一部分进入地球本影，亮面被"啃"掉一块，缺口的边缘总是圆弧形——那正是地球的影子。古人正是靠这一点推断地球是个球。';
  if (st.lunar.type === 'penumbral')
    return '半影月食：月亮只进入地球的半影，亮度稍微变暗一点，肉眼不太容易看出来。月食一定发生在农历十五、十六（望）。';
  const near = Math.min(st.elong, 360 - st.elong);
  if (near < 20 && !st.solar.type)
    return `现在是朔（初一）附近，月球就在太阳的方向上。可是月球轨道相对地球轨道倾斜了约 5°，此刻月球偏在黄道面 ${(st.moon.lat * R2D).toFixed(1)}°，影子从地球上方或下方掠过去了，所以没有日食。`;
  if (Math.abs(st.elong - 180) < 20 && !st.lunar.type)
    return `现在是望（十五）附近，地球就在太阳和月球中间。可是月球此刻偏在黄道面 ${(st.moon.lat * R2D).toFixed(1)}°，从地影的上方或下方绕过去了，所以没有月食。大约每半年才有一次"食季"。`;
  const map = {
    '新月': '新月（朔）：月球运行到太阳和地球之间，被照亮的那一面完全背对我们，所以几乎看不见它。农历初一就是"朔日"。如果这时月球恰好在黄道面附近，就会发生日食。',
    '蛾眉月': '蛾眉月：日落后出现在西方低空，像一道弯弯的眉毛。注意看，亮的一面总是朝着太阳落下的方向——记住这条规律，就不会把月相看反了。',
    '上弦月': '上弦月：日月角距正好 90°，我们看到月亮被照亮了一半。它中午升起，黄昏时挂在南方天空，半夜落下。大致是农历初七、初八。',
    '盈凸月': '盈凸月：亮面超过一半，还在继续变大，快要到满月了。这时月亮傍晚就已经在东南方天空，半夜才落。',
    '满月': '满月（望）：地球跑到太阳和月球中间，我们看到整个被照亮的半球。它日落时升起、日出时落下，整夜可见。大致是农历十五、十六。',
    '亏凸月': '亏凸月：满月之后亮面一天天变小。月亮升起的时间越来越晚，后半夜才看得到。',
    '下弦月': '下弦月：又只剩一半亮面，不过这次亮的换到了另一边（北半球看是左半边）。它半夜升起，清晨挂在南方天空。大致是农历廿二、廿三。',
    '残月': '残月：清晨东方低空的一弯细月，之后月亮回到太阳的方向，新一轮的阴晴圆缺又要开始了。',
  };
  return map[st.phase.short] || '拖动时间，看看月亮的阴晴圆缺是怎么变化的。';
}
